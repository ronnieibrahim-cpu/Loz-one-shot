// Sprite pack: bosses (32x32) and minibosses (24x24).
//
// Art grammar: see src/gfx/art.js ('.' transparent, '0'..'3' light to dark).
// Required names: see REQUIRED_SPRITES.bosses / .minibosses in
// src/data/sprite-manifest.js.
//
// Drawn by hand, cell by cell, to docs/ART-DIRECTION.md: silhouette first, a
// hard 1px '3' outline all the way round, a flat 0/1/2 light-to-dark ramp with
// no gradients or dithering, and one clear focal point — the eye, mouth or core
// the player aims at. Roughly two thirds of the cell is filled so each reads
// against any floor.
//
// Frames are an idle cycle, not directions: defineBoss takes a plain frames
// array, so every pose has to read the same from any angle. Appendages (claws,
// tentacles, wings, drips) carry the animation while the body stays put, which
// keeps the silhouette stable and puts the 3px-minimum difference somewhere the
// eye actually tracks. The _hurt frame is the same creature caught mid-recoil —
// eyes shut or squinted, body flinched a pixel — and is only shown while it is
// flickering from a hit.
//
// Palettes come from the boss definitions in src/data/bosses.js (gohmaraq
// 'enemyr', anemos 'coral', gloomtide 'bog', wyverna 'enemyb', rootmaw
// 'treedk', brinehulk 'marble', thalassor 'reef', nereth 'abyss'), so index 0
// is the highlight, 1 the body, 2 the shadow and 3 the outline in every case.

