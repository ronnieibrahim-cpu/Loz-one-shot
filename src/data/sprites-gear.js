// does not; these are the "draw to match" half, and the target was measured off
// the 18 extracted 16x16 icons in sprites-hud.js rather than eyeballed:
//
//   content   median 8 wide x 15 tall (range 6-12 x 9-16), centred in the cell
//   fill      ~30% of the cell — gear icons are slender portraits, not the
//             two-thirds coverage ART-DIRECTION specifies for creatures
//   colours   2-3 plus pure black, with a hard 1px black outline all the way
//             round; index 0 highlight, 1 body, 3 outline
//
// i_bomb_lit is the extracted bomb pixel for pixel with its fuse alight, so it
// cannot drift from the sprite it has to sit next to.
//
// Each sprite binds its own palette, like the extracted ones, so draw sites must
// NOT pass a palette for these names — art.js bake() resolves `palName || d.pal`
// and an explicit palette would override the bound one.

