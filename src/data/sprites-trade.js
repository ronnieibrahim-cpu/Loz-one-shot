// Egg, the Ghastly Doll — and every one of them is a thing that game is about.
// Extracting them would have imported the other game's design, which is the one
// borrowing CLAUDE.md forbids: the surface is theirs, the subject is ours. The
// PEOPLE holding these are extracted (see sprites-npcs.js and sprites-races.js);
// the objects are drawn to match them, at the register docs/ART-DIRECTION.md
// sets — three colours plus transparency, a hard 1px black outline, no
// anti-aliasing, and a silhouette that reads in pure black at 16x16.
//
// Every one of them is a working object off this coast: a float, a claw, a
// brick of pan salt. Nothing in the chain is a treasure until the last link,
// which is the point of the chain.

